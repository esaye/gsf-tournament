sub Run ($$@) { 
  my $this = shift;
  my $tournament = shift;
  my $dp = pop @_;
  my $count = @_ ? pop @_ : 1;
  my $config = $tournament->Config();
  my $c_final_draw = $config->Value('final_draw');

  my $datap = $dp->{'data'};
# my $nplayers = $#$datap;

  my $max_rounds = $dp->MaxRound0();
  if (!defined $max_rounds) {
    $tournament->TellUser("eneed_max_rounds");
    return 0;
    }
  # check that division is not partially paired
  my $round0 = $dp->FirstUnpairedRound0();
  if ($round0 != $dp->LastPairedRound0()+1) {
    $tournament->TellUser('errpartp');
    return;
    }
# TSH::Player::SpliceInactive @$unpaired, $nplayers-1;

  my $psp = $dp->GetUnpairedRound($round0);
  my $need_bye = @$psp % 2;
  my $nplayers = scalar(@$psp);
  my $schedule_size = $nplayers + $need_bye;
  # interleave_rr = 0 or unspecified defaults to = 1
  # interleave_rr = 1 if player plays all opponents once before repeat
  # interleave_rr = 2 if player plays all opponents twice before repeat 
  my $interleave_count = $dp->GetConfigValue('interleave_rr') || 1;
  if ($max_rounds) {
    my $rr_length = $schedule_size - 1;
    my $last_round = $interleave_count * $count * $rr_length + $round0 - 1;
#   warn "$interleave_count $count $rr_length $round0 $last_round $max_rounds";
    if ($last_round > $max_rounds) {
      $tournament->TellUser('ebigrd', $last_round+1, $max_rounds+1);
      return;
      }
    }
  $tournament->TellUser('irrcok', $dp->{'name'});
  # $p2sv1: 2 if p2 should start vs p1, -2 if p1 should start, 1 if don't care
  my $p2sv1 = 0;
  for (my $r0 = 0; ; $r0++) {
    my $p1oid = $psp->[0]->OpponentID($r0);
    last unless defined $p1oid;
    next unless $p1oid == $psp->[1]->ID();
    if (1 == (my $this_first = $psp->[0]->First($r0))) { $p2sv1++; }
    elsif ($this_first == 2) { $p2sv1--; }
    }
  $p2sv1 = (2 * ($p2sv1 <=> 0) || 1);
  # add pairings information one round at a time
  my (@oppi) = @{
    $config->Value('round_robin_order') || do {
#     my @order; # (n n-1 n-3 ... 7 5 3 4 6 8 ... n-4 n-2)
#     for (my $i = 3; $i < $schedule_size-2; ) {
#	unshift(@order, $i++);
#	push(@order, $i++);
#	}
#     unshift(@order, $schedule_size, $schedule_size-1);
#     push(@order, 2);
      my @order = (2); # (n n-1 | n n-2 n-3 n-3), (... 10 8 9 7 6 4 5 3), (2)
      for (my $i=3; $i<=$schedule_size-3; $i+=4) {
#	unshift(@order, $i+3, $i+1, $i+2, $i);
 	unshift(@order, $i+3, $i+2, $i+1, $i); # 2014-05-24: not sure why these were swapped above
        }
      if ($schedule_size % 4 == 0) {
	unshift(@order, $schedule_size, $schedule_size-1);
	}
      \@order;
      };
    };
# die "@oppi";
  if ($config->Value('random_rr_order')) {
    # Knuth shuffle
    my $n = scalar(@oppi);
    while (--$n > 0) {
      my $k = int(rand()*($n+1));
      @oppi[$n,$k] = @oppi[$k,$n];
      }
    }

  for my $j (1..$count) {
    for my $oppi (@oppi) {
      for my $k (1..$interleave_count) {
	my $assign_firsts = $p2sv1 * (($j+$k+1) % 2 ? 1 : -1);
	if ($c_final_draw and $round0 == $max_rounds) { $assign_firsts = 0; }
	#	warn "$c_final_draw $round0 $max_rounds $assign_firsts";
	TSH::Division::Pairing::Berger::PairGroup 
	  $dp->GetUnpairedRound($round0++),
	  $oppi,
	  {
	    'assign_firsts' => $assign_firsts,
	    'koth' => 1,
	  }
	}
      }
    }

  $tournament->TellUser('idone');

  $dp->Dirty(1);
  $this->Processor()->Flush();
  }

